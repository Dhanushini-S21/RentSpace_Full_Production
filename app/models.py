from datetime import datetime, timezone
from . import db

def now():
    return datetime.now(timezone.utc)

class User(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    email = db.Column(db.String(255), unique=True, nullable=False, index=True)
    name = db.Column(db.String(150), nullable=False)
    role = db.Column(db.String(20), nullable=False, index=True)
    password_hash = db.Column(db.String(255), nullable=False)
    active = db.Column(db.Boolean, default=True, nullable=False)
    admin_made_changes = db.Column(db.Boolean, default=False, nullable=False)
    created_at = db.Column(db.DateTime(timezone=True), default=now)

class OwnerProfile(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("user.id"), unique=True, nullable=False)
    age = db.Column(db.Integer)
    own_location = db.Column(db.String(255))
    phone = db.Column(db.String(30))
    email_id = db.Column(db.String(255))
    aadhaar_number = db.Column(db.String(255))
    aadhaar_photo_path = db.Column(db.String(500))
    matched_tenants = db.Column(db.Integer, default=0, nullable=False)
    scheduled_visits = db.Column(db.Integer, default=0, nullable=False)
    times_visited = db.Column(db.Integer, default=0, nullable=False)
    tenant_feedback = db.Column(db.Text)
    current_scheduled_visit = db.Column(db.DateTime(timezone=True))
    verified = db.Column(db.Boolean, default=False, nullable=False)
    booked = db.Column(db.Boolean, default=False, nullable=False)
    issues = db.Column(db.Text)
    enquiry = db.Column(db.Text)
    user = db.relationship("User", backref=db.backref("owner_profile", uselist=False))

class TenantProfile(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    user_id = db.Column(db.Integer, db.ForeignKey("user.id"), unique=True, nullable=False)
    tid = db.Column(db.String(20), unique=True, index=True)
    age = db.Column(db.Integer)
    mobile = db.Column(db.String(30))
    email_id = db.Column(db.String(255))
    native_location = db.Column(db.String(255))
    current_location = db.Column(db.String(255))
    aadhaar_photo_path = db.Column(db.String(500))
    purpose = db.Column(db.String(80))
    purpose_other = db.Column(db.String(255))
    people_type = db.Column(db.String(255))
    min_people = db.Column(db.Integer)
    max_people = db.Column(db.Integer)
    needed_property_type = db.Column(db.String(50))
    min_rent = db.Column(db.Numeric(12, 2))
    max_rent = db.Column(db.Numeric(12, 2))
    min_advance = db.Column(db.Numeric(12, 2))
    max_advance = db.Column(db.Numeric(12, 2))
    bedrooms_needed = db.Column(db.Integer)
    halls_needed = db.Column(db.Integer)
    bathrooms_needed = db.Column(db.Integer)
    kitchens_needed = db.Column(db.Integer)
    rental_min_duration = db.Column(db.String(50))
    rental_max_duration = db.Column(db.String(50))
    two_wheeler_count = db.Column(db.Integer, default=0)
    four_wheeler_count = db.Column(db.Integer, default=0)
    needed_type = db.Column(db.String(50))
    needed_date = db.Column(db.Date)
    preferred_locations = db.Column(db.Text)
    preferred_landmarks = db.Column(db.Text)
    free_hours_from = db.Column(db.String(10))
    free_hours_to = db.Column(db.String(10))
    other_preferences = db.Column(db.Text)
    matched_rental_spaces = db.Column(db.Integer, default=0, nullable=False)
    scheduled_visits = db.Column(db.Integer, default=0, nullable=False)
    allocated_property_id = db.Column(db.Integer, db.ForeignKey("property.id"))
    confirmed_property_id = db.Column(db.Integer, db.ForeignKey("property.id"))
    current_scheduled_visit = db.Column(db.DateTime(timezone=True))
    admin_feedback = db.Column(db.Text)
    tenant_feedback = db.Column(db.Text)
    verified = db.Column(db.Boolean, default=False, nullable=False)
    issues = db.Column(db.Text)
    enquiry = db.Column(db.Text)
    user = db.relationship("User", backref=db.backref("tenant_profile", uselist=False))

class Property(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    hid = db.Column(db.String(20), unique=True, index=True)
    owner_id = db.Column(db.Integer, db.ForeignKey("user.id"), nullable=False, index=True)
    title = db.Column(db.String(200), nullable=False)
    property_type = db.Column(db.String(50), nullable=False)
    location = db.Column(db.String(255), nullable=False, index=True)
    rent = db.Column(db.Numeric(12, 2), nullable=False)
    advance = db.Column(db.Numeric(12, 2), nullable=False)
    furnished_status = db.Column(db.String(50), default="not_available")
    furnished_items = db.Column(db.Text)
    electricity_type = db.Column(db.String(100))
    borewell_water = db.Column(db.String(30))
    drinking_water = db.Column(db.String(30))
    bedroom_count = db.Column(db.Integer, default=0)
    hall_count = db.Column(db.Integer, default=0)
    kitchen_count = db.Column(db.Integer, default=0)
    pooja_room_count = db.Column(db.Integer, default=0)
    bathrooms = db.Column(db.Integer, default=0)
    allowed_people_types = db.Column(db.Text)
    min_people = db.Column(db.Integer)
    max_people = db.Column(db.Integer)
    two_wheeler_count = db.Column(db.Integer, default=0)
    four_wheeler_count = db.Column(db.Integer, default=0)
    area_sqft = db.Column(db.Integer)
    construction_year = db.Column(db.Integer)
    facing = db.Column(db.String(50))
    availability_type = db.Column(db.String(50))
    availability_date = db.Column(db.Date)
    landmarks = db.Column(db.Text)
    rental_min_duration = db.Column(db.String(50))
    rental_max_duration = db.Column(db.String(50))
    free_hours_from = db.Column(db.String(10))
    free_hours_to = db.Column(db.String(10))
    conditions = db.Column(db.Text)
    status = db.Column(db.String(30), default="pending", index=True)
    currently_available = db.Column(db.Boolean, default=True, index=True)
    created_at = db.Column(db.DateTime(timezone=True), default=now)
    updated_at = db.Column(db.DateTime(timezone=True), default=now, onupdate=now)
    owner = db.relationship("User", backref="properties")

class Inquiry(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    property_id = db.Column(db.Integer, db.ForeignKey("property.id"), nullable=False)
    tenant_id = db.Column(db.Integer, db.ForeignKey("user.id"), nullable=False)
    message = db.Column(db.Text)
    status = db.Column(db.String(30), default="new", index=True)
    created_at = db.Column(db.DateTime(timezone=True), default=now)
    property = db.relationship("Property", backref="inquiries")
    tenant = db.relationship("User", backref="inquiries")

class Favorite(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    property_id = db.Column(db.Integer, db.ForeignKey("property.id"), nullable=False)
    tenant_id = db.Column(db.Integer, db.ForeignKey("user.id"), nullable=False)
    created_at = db.Column(db.DateTime(timezone=True), default=now)

class Issue(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    reporter_id = db.Column(db.Integer, db.ForeignKey("user.id"), nullable=False)
    property_id = db.Column(db.Integer, db.ForeignKey("property.id"))
    category = db.Column(db.String(80), nullable=False)
    description = db.Column(db.Text, nullable=False)
    status = db.Column(db.String(30), default="open", index=True)
    created_at = db.Column(db.DateTime(timezone=True), default=now)

class ChangeNotification(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    recipient_role = db.Column(db.String(20), nullable=False, index=True)
    actor_id = db.Column(db.Integer, db.ForeignKey("user.id"))
    entity_type = db.Column(db.String(50), nullable=False)
    entity_id = db.Column(db.Integer, nullable=False)
    message = db.Column(db.Text, nullable=False)
    is_read = db.Column(db.Boolean, default=False, nullable=False, index=True)
    created_at = db.Column(db.DateTime(timezone=True), default=now, index=True)
    actor = db.relationship("User", foreign_keys=[actor_id])

class Event(db.Model):
    id = db.Column(db.Integer, primary_key=True)
    actor_id = db.Column(db.Integer, db.ForeignKey("user.id"))
    event_type = db.Column(db.String(100), nullable=False, index=True)
    entity_type = db.Column(db.String(100))
    entity_id = db.Column(db.Integer)
    message = db.Column(db.Text)
    created_at = db.Column(db.DateTime(timezone=True), default=now, index=True)
